import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { emptyData } from '../src/lib/types.ts';
const a='11111111-1111-4111-8111-111111111111',b='22222222-2222-4222-8222-222222222222';
test('PostgreSQL migration enforces RLS, import idempotency, revisions and atomic external-action reservations',async()=>{
 const pg=new PGlite();
 try{
 await pg.exec(`create role anon; create role authenticated; create role service_role bypassrls; create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$; grant usage on schema public,auth to authenticated,anon,service_role; grant execute on function auth.uid() to authenticated;`);
 await pg.exec(await readFile(new URL('../supabase/migrations/001_core.sql',import.meta.url),'utf8'));
 await pg.exec(await readFile(new URL('../supabase/migrations/002_scheduler.sql',import.meta.url),'utf8'));
 await pg.exec(await readFile(new URL('../supabase/migrations/003_dispatch_claim.sql',import.meta.url),'utf8'));
 await pg.exec(await readFile(new URL('../supabase/migrations/004_atomic_accountability.sql',import.meta.url),'utf8'));
 await pg.exec(`grant all on all tables in schema public to service_role; insert into auth.users values ('${a}'),('${b}');`);
 await pg.exec(`set role authenticated;set request.jwt.claim.sub='${a}';`);
 const doc=emptyData();
 const save=()=>pg.query('select public.save_workspace($1::jsonb,$2,$3::jsonb,$4) as revision',[JSON.stringify(doc),0,'[]',true]);
 assert.equal((await save()).rows.length,1);
 await assert.rejects(save());
 assert.equal((await pg.query('select * from public.study_documents')).rows.length,1);
 await assert.rejects(pg.query('select public.save_workspace($1::jsonb,1,$2::jsonb,true)',[JSON.stringify(doc),'[]']));
 await pg.exec(`set request.jwt.claim.sub='${b}';`);
 assert.equal((await pg.query('select * from public.study_documents')).rows.length,0);
 assert.equal((await pg.query('select * from public.problems')).rows.length,0);
 await assert.rejects(pg.query(`update public.study_documents set revision=99 where user_id='${a}'`));
 await pg.query('select public.save_workspace($1::jsonb,0,$2::jsonb,false)',[JSON.stringify(doc),'[]']);
 assert.equal((await pg.query('select * from public.study_documents')).rows.length,1);
 await pg.exec('reset role;');
 await pg.query("insert into public.fo_connections(user_id,encrypted) values($1,'ciphertext')",[a]);
 await pg.exec(`set role authenticated;set request.jwt.claim.sub='${a}';`);
 await assert.rejects(pg.query('select * from public.fo_connections'));
 await assert.rejects(pg.query('truncate public.study_documents'));
 await assert.rejects(pg.query('select public.disconnect_fo($1)',[a]));
 await assert.rejects(pg.query('select public.acquire_fo_lock($1,$2)',[a,b]));
 await pg.exec('reset role;set role service_role;');
 assert.equal((await pg.query<{acquire_fo_lock:boolean}>('select public.acquire_fo_lock($1,$2)',[a,b])).rows[0].acquire_fo_lock,true);
 assert.equal((await pg.query<{acquire_fo_lock:boolean}>('select public.acquire_fo_lock($1,$2)',[a,b])).rows[0].acquire_fo_lock,false);
 await pg.query("insert into public.fo_requests(user_id,dedupe_key,kind,instructions) values($1,'once','text','hello')",[a]);
 await assert.rejects(pg.query("insert into public.fo_requests(user_id,dedupe_key,kind,instructions) values($1,'once','text','hello')",[a]));
 const requestId=(await pg.query<{id:string}>("select id from public.fo_requests where user_id=$1",[a])).rows[0].id;
 assert.equal((await pg.query('select * from public.claim_fo_request($1,$2)',[b,requestId])).rows.length,0);
 assert.equal((await pg.query('select * from public.claim_fo_request($1,$2)',[a,requestId])).rows.length,1);
 assert.equal((await pg.query('select * from public.claim_fo_request($1,$2)',[a,requestId])).rows.length,0);
 assert.equal((await pg.query("update public.fo_requests set status='sending' where user_id=$1 and status='queued' returning id",[a])).rows.length,0);
 const stale=(await pg.query<{id:string}>("insert into public.fo_requests(user_id,dedupe_key,kind,instructions,source_revision) values($1,'missed-stale','missed','check in',999) returning id",[a])).rows[0].id;
 await pg.query("insert into public.accountability_preferences(user_id,enabled,consent_at) values($1,true,now())",[a]);
 assert.equal((await pg.query('select * from public.claim_fo_request($1,$2)',[a,stale])).rows.length,0);
 assert.equal((await pg.query<{status:string}>('select status from public.fo_requests where id=$1',[stale])).rows[0].status,'cancelled');
 await pg.query("insert into public.fo_oauth_flows values('state',$1,'cipher',now()+interval '1 minute')",[a]);
 assert.equal((await pg.query("delete from public.fo_oauth_flows where state_hash='state' and user_id=$1 returning state_hash",[b])).rows.length,0);
 assert.equal((await pg.query("delete from public.fo_oauth_flows where state_hash='state' and user_id=$1 returning state_hash",[a])).rows.length,1);
 assert.equal((await pg.query("delete from public.fo_oauth_flows where state_hash='state' and user_id=$1 returning state_hash",[a])).rows.length,0);

 const queued=(await pg.query<{id:string}>("insert into public.fo_requests(user_id,dedupe_key,kind,instructions) values($1,'cancel-me','text','hello') returning id",[a])).rows[0].id;
 await assert.rejects(pg.query('select public.set_accountability_preferences($1,false,$2,21,9,99)',[a,'UTC']));
 assert.equal((await pg.query<{status:string}>('select status from public.fo_requests where id=$1',[queued])).rows[0].status,'queued');
 await pg.query('select public.set_accountability_preferences($1,false,$2,21,9,1)',[a,'UTC']);
 assert.equal((await pg.query<{status:string}>('select status from public.fo_requests where id=$1',[queued])).rows[0].status,'cancelled');
 await pg.query("insert into public.fo_connections(user_id,encrypted) values($1,'other-account')",[b]);
 await pg.query('select public.disconnect_fo($1)',[a]);
 assert.equal((await pg.query('select * from public.fo_connections where user_id=$1',[a])).rows.length,0);
 assert.equal((await pg.query('select * from public.fo_connections where user_id=$1',[b])).rows.length,1);
 assert.equal((await pg.query<{status:string}>('select status from public.fo_requests where id=$1',[requestId])).rows[0].status,'sending');
 }finally{await pg.close();}
});
